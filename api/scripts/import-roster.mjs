#!/usr/bin/env node
/**
 * Roster importer — turns the official registration Excel into a D1 seed file.
 *
 *   node scripts/import-roster.mjs \
 *     --file "C:/Users/imtia/Downloads/2026 Summer CSE Registration _ Advising List [v1] [Student].xlsx" \
 *     --out scripts/out/roster_seed.sql
 *
 * Reads the `StudentList` sheet, auto-detects the header row + the "Student ID"
 * column (no hardcoded layout), validates IDs (numeric, length auto-detected),
 * dedupes, and writes INSERTs that store each ID as HMAC-SHA256 — the raw IDs
 * never touch the database.
 *
 * Apply the output with:
 *   wrangler d1 execute bracu_vault --local --file scripts/out/roster_seed.sql
 *
 * Flags:
 *   --file <path>     source xlsx (defaults to the known Downloads path)
 *   --out  <path>     output SQL (default scripts/out/roster_seed.sql)
 *   --sheet <name>    sheet name (default "StudentList")
 *   --secret <key>    HMAC key (else env ROSTER_HMAC_SECRET). Must match the Worker.
 *   --dry             analyze + report only; no file written, no secret required
 */

import { createHash, createHmac, randomUUID } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import * as XLSX from "xlsx";

const VALID_ID_LENGTHS = new Set([8, 10]); // matches src/services/roster.service.ts

function arg(name, fallback) {
  const i = process.argv.indexOf(`--${name}`);
  return i !== -1 && process.argv[i + 1] ? process.argv[i + 1] : fallback;
}
const hasFlag = (name) => process.argv.includes(`--${name}`);

const FILE = arg(
  "file",
  "C:/Users/imtia/Downloads/2026 Summer CSE Registration _ Advising List [v1] [Student].xlsx",
);
const OUT = arg("out", "scripts/out/roster_seed.sql");
const SHEET = arg("sheet", "StudentList");
const DRY = hasFlag("dry");
const SECRET = arg("secret", process.env.ROSTER_HMAC_SECRET);

if (!DRY && !SECRET) {
  console.error("✖ Missing HMAC secret. Pass --secret or set ROSTER_HMAC_SECRET (or use --dry).");
  process.exit(1);
}

const sqlStr = (s) => `'${String(s).replace(/'/g, "''")}'`;

function findColumn(rows) {
  // Scan the first 15 rows for a cell that looks like the "Student ID" header.
  for (let r = 0; r < Math.min(rows.length, 15); r++) {
    const row = rows[r] ?? [];
    for (let c = 0; c < row.length; c++) {
      const v = (row[c] ?? "").toString().trim().toLowerCase();
      if (v === "student id") return { headerRow: r, col: c };
    }
  }
  return null;
}

function main() {
  const buf = readFileSync(FILE);
  const fileSha = createHash("sha256").update(buf).digest("hex");
  const wb = XLSX.read(buf, { type: "buffer" });
  const ws = wb.Sheets[SHEET];
  if (!ws) {
    console.error(`✖ Sheet "${SHEET}" not found. Available: ${wb.SheetNames.join(", ")}`);
    process.exit(1);
  }

  const rows = XLSX.utils.sheet_to_json(ws, { header: 1, raw: true, defval: null });
  const found = findColumn(rows);
  if (!found) {
    console.error('✖ Could not locate a "Student ID" header in the first 15 rows.');
    process.exit(1);
  }

  const seen = new Set();
  const valid = [];
  const formats = {};
  let skippedBlank = 0;
  let skippedMalformed = 0;
  let dupes = 0;

  for (let r = found.headerRow + 1; r < rows.length; r++) {
    const raw = rows[r]?.[found.col];
    if (raw === null || raw === undefined || raw === "") {
      skippedBlank++;
      continue;
    }
    const id = String(raw).trim();
    if (!/^\d+$/.test(id) || !VALID_ID_LENGTHS.has(id.length)) {
      skippedMalformed++;
      continue;
    }
    if (seen.has(id)) {
      dupes++;
      continue;
    }
    seen.add(id);
    formats[id.length] = (formats[id.length] ?? 0) + 1;
    valid.push(id);
  }

  console.log("── Roster import summary ─────────────────────────────");
  console.log("  file        :", FILE);
  console.log("  sha256      :", fileSha);
  console.log("  sheet       :", SHEET, `(header row ${found.headerRow + 1}, column ${found.col})`);
  console.log("  valid IDs   :", valid.length);
  console.log("  by length   :", JSON.stringify(formats));
  console.log("  skipped     :", { blank: skippedBlank, malformed: skippedMalformed, duplicate: dupes });

  if (DRY) {
    console.log("\n(dry run — no SQL written)");
    return;
  }

  const importId = randomUUID();
  const lines = [];
  lines.push("-- Generated by scripts/import-roster.mjs — do not edit by hand.");
  lines.push("PRAGMA foreign_keys = ON;");
  lines.push(
    `INSERT INTO roster_imports (id, filename, row_count, sha256) VALUES (${sqlStr(importId)}, ${sqlStr(FILE.split(/[\\/]/).pop())}, ${valid.length}, ${sqlStr(fileSha)});`,
  );

  const CHUNK = 500;
  for (let i = 0; i < valid.length; i += CHUNK) {
    const slice = valid.slice(i, i + CHUNK);
    const values = slice
      .map((id) => {
        const hmac = createHmac("sha256", SECRET).update(id).digest("hex");
        return `(${sqlStr(randomUUID())}, ${sqlStr(hmac)}, ${id.length}, NULL, ${sqlStr(importId)})`;
      })
      .join(",\n  ");
    lines.push(
      `INSERT INTO student_roster (id, student_id_hmac, id_format, sl, import_id) VALUES\n  ${values};`,
    );
  }

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, lines.join("\n") + "\n", "utf8");
  console.log(`\n✔ Wrote ${valid.length} rows → ${OUT}`);
  console.log("  apply: wrangler d1 execute bracu_vault --local --file", OUT);
}

main();
